/**
 * Builds the design tokens (tokens.json) into CSS:
 * - dist/tokens.css: --trv-* variables, light by default, dark through prefers-color-scheme
 *   or data-theme="dark" (data-theme="light" forces light);
 * - dist/theme.css: a Tailwind 4 `@theme` mapping onto those variables.
 * Run: node src/build.ts
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

interface ThemedColor {
  light: string;
  dark: string;
}

export interface Tokens {
  color: Record<string, ThemedColor>;
  radius: Record<string, string>;
  space: Record<string, string>;
  shadow: Record<string, string>;
  motion: Record<string, string>;
  easing: Record<string, string>;
  font: Record<string, string>;
}

const SCALAR_GROUPS = ["radius", "space", "shadow", "motion", "easing", "font"] as const;

function declarations(entries: [string, string][]): string {
  return entries.map(([name, value]) => `  --trv-${name}: ${value};`).join("\n");
}

function colors(tokens: Tokens, mode: keyof ThemedColor): [string, string][] {
  return Object.entries(tokens.color).map(([name, value]) => [`color-${name}`, value[mode]]);
}

export function buildTokensCss(tokens: Tokens): string {
  const scalars = SCALAR_GROUPS.flatMap((group) =>
    Object.entries(tokens[group]).map(([name, value]): [string, string] => [
      `${group}-${name}`,
      value,
    ]),
  );
  const dark = declarations(colors(tokens, "dark")).replaceAll("\n  ", "\n    ");
  return [
    "/* Generated by @trovelya/design-tokens from tokens.json. Do not edit. */",
    `:root {\n${declarations([...colors(tokens, "light"), ...scalars])}\n  color-scheme: light;\n}`,
    `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n  ${dark}\n    color-scheme: dark;\n  }\n}`,
    `:root[data-theme="dark"] {\n${declarations(colors(tokens, "dark"))}\n  color-scheme: dark;\n}`,
    "",
  ].join("\n");
}

const THEME_PREFIX: Record<(typeof SCALAR_GROUPS)[number] | "color", string> = {
  color: "color",
  radius: "radius",
  space: "spacing",
  shadow: "shadow",
  motion: "duration",
  easing: "ease",
  font: "font",
};

export function buildThemeCss(tokens: Tokens): string {
  const groups = ["color", ...SCALAR_GROUPS] as const;
  const lines = groups.flatMap((group) =>
    Object.keys(tokens[group]).map(
      (name) => `  --${THEME_PREFIX[group]}-${name}: var(--trv-${group}-${name});`,
    ),
  );
  return [
    "/* Generated by @trovelya/design-tokens from tokens.json. Do not edit. */",
    `@theme inline {\n${lines.join("\n")}\n}`,
    "",
  ].join("\n");
}

function main(): void {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..");
  const tokens = JSON.parse(readFileSync(join(root, "tokens.json"), "utf8")) as Tokens;
  mkdirSync(join(root, "dist"), { recursive: true });
  writeFileSync(join(root, "dist", "tokens.css"), buildTokensCss(tokens));
  writeFileSync(join(root, "dist", "theme.css"), buildThemeCss(tokens));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main();
}
